  function toJD(y, m, d, hh, mm) {
    hh = hh || 0; mm = mm || 0;
    if (m <= 2) { y -= 1; m += 12; }
    var A = Math.floor(y / 100);
    var B = 2 - A + Math.floor(A / 4);
    var day = Math.floor(365.25 * (y + 4716)) + Math.floor(30.6001 * (m + 1)) + d + B - 1524.5;
    day += (hh + mm / 60) / 24;
    return day;
  }

